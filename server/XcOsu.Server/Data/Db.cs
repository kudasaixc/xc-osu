// xc-osu! server: PostgreSQL persistence. xc softworks (kudasaixc)
//
// One pooled data source for the whole process: every request borrows a connection for a few statements and hands it
// back, so hundreds of simultaneous clients share a bounded set of server backends and never wait on a single writer.

using System.Globalization;
using Npgsql;
using NpgsqlTypes;

namespace XcOsu.Server.Data
{
    public sealed class Db : IDisposable
    {
        /// <summary>Where the server reaches PostgreSQL when nothing is configured: the local socket, as the account running the process.</summary>
        public const string DEFAULT_CONNECTION = "Host=/var/run/postgresql;Database=xc_osu";

        private readonly NpgsqlDataSource source;

        public Db(IConfiguration config)
        {
            string dir = config["DataDirectory"] ?? "/var/lib/xc-osu";
            Directory.CreateDirectory(dir);
            DataDirectory = dir;

            var cs = new NpgsqlConnectionStringBuilder(config["Database:ConnectionString"] ?? DEFAULT_CONNECTION);
            // a builder reports every keyword as "contained" once it holds the driver default: only an explicitly written
            // keyword must win over ours.
            void fallback(string key, object value) { if (!cs.ShouldSerialize(key)) cs[key] = value; }
            fallback("Pooling", true);
            fallback("Minimum Pool Size", 4);
            fallback("Maximum Pool Size", 120);
            fallback("Timeout", 15);
            fallback("Command Timeout", 30);
            // the same few hundred statements run all day: let the driver prepare the hot ones once per connection.
            fallback("Max Auto Prepare", 200);
            fallback("Auto Prepare Min Usages", 3);
            fallback("Application Name", "xc-osu-server");
            source = new NpgsqlDataSourceBuilder(cs.ConnectionString).Build();

            migrate();
        }

        /// <summary>Files that stay on disk (avatars, covers, team flags, cached .osu files, replays).</summary>
        public string DataDirectory { get; }

        public NpgsqlConnection Open() => source.OpenConnection();

        private void migrate()
        {
            using var c = Open();
            // two processes starting together (a test instance, an operator command) must not race on CREATE.
            exec(c, "SELECT pg_advisory_lock(7203119)");

            // citext: user names, addresses and team names compare, sort and stay unique without regard to case.
            exec(c, "CREATE EXTENSION IF NOT EXISTS citext");
            // this connection loaded its type catalog before the extension existed on a fresh database: teach it citext now,
            // so reads of user names do not fail until the pool hands out a newer connection.
            c.ReloadTypes();

            exec(c, """
                -- osu!lazer treats user ids <= 1 as "no user" (guest / system): like osu-web, real accounts start at 2.
                CREATE TABLE IF NOT EXISTS users (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
                    username CITEXT NOT NULL UNIQUE,
                    email CITEXT NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    country TEXT NOT NULL DEFAULT 'XX',
                    join_date TEXT NOT NULL,
                    last_visit TEXT,
                    is_admin BIGINT NOT NULL DEFAULT 0,
                    title TEXT,
                    playmode TEXT NOT NULL DEFAULT 'osu',
                    email_verified BIGINT NOT NULL DEFAULT 0,
                    -- accounts created before email confirmation became a condition keep their abilities; new ones must confirm.
                    verification_required BIGINT NOT NULL DEFAULT 0,
                    avatar_version BIGINT NOT NULL DEFAULT 0,
                    cover_version BIGINT NOT NULL DEFAULT 0,
                    silenced_until TEXT,
                    restricted BIGINT NOT NULL DEFAULT 0,
                    previous_usernames TEXT NOT NULL DEFAULT '[]',
                    profile_json TEXT NOT NULL DEFAULT '{}',
                    rank_highest BIGINT,
                    rank_highest_at TEXT
                );
                -- every token pair belongs to one session; a rotation keeps the id, a sign-out or revocation ends it.
                CREATE TABLE IF NOT EXISTS tokens (
                    access_token TEXT PRIMARY KEY,
                    refresh_token TEXT NOT NULL UNIQUE,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    expires_at BIGINT NOT NULL,
                    refresh_expires_at BIGINT NOT NULL DEFAULT 0,
                    session_expires_at BIGINT NOT NULL DEFAULT 0,
                    session_id TEXT
                );
                CREATE INDEX IF NOT EXISTS ix_tokens_session ON tokens(session_id);
                CREATE INDEX IF NOT EXISTS ix_tokens_user ON tokens(user_id);
                CREATE TABLE IF NOT EXISTS password_resets (
                    token_hash TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    expires_at BIGINT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS account_challenges (
                    token_hash TEXT PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    purpose TEXT NOT NULL,
                    expires_at BIGINT NOT NULL
                );
                CREATE TABLE IF NOT EXISTS score_tokens (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
