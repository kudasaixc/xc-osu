                    created_at BIGINT NOT NULL,
                    score_id BIGINT,
                    beatmap_hash TEXT,
                    room_id BIGINT
                );
                -- verification: 0 pending, 1 verified, 2 replay does not reproduce the score, 3 could not be simulated, 4 no replay delivered.
                CREATE TABLE IF NOT EXISTS scores (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                    beatmap_id BIGINT NOT NULL,
                    ruleset_id BIGINT NOT NULL,
                    playlist_item_id BIGINT,
                    total_score BIGINT NOT NULL,
                    accuracy DOUBLE PRECISION NOT NULL,
                    max_combo BIGINT NOT NULL,
                    rank TEXT NOT NULL,
                    passed BIGINT NOT NULL,
                    pp DOUBLE PRECISION,
                    ranked BIGINT NOT NULL DEFAULT 0,
                    mods TEXT NOT NULL,
                    data TEXT NOT NULL,
                    ended_at TEXT NOT NULL,
                    has_replay BIGINT NOT NULL DEFAULT 0,
                    verification BIGINT NOT NULL DEFAULT 0,
                    replay_due BIGINT,
                    started_at TEXT,
                    total_hits BIGINT NOT NULL DEFAULT 0,
                    play_seconds BIGINT NOT NULL DEFAULT 0,
                    legacy_total_score BIGINT NOT NULL DEFAULT 0
                );
                CREATE INDEX IF NOT EXISTS ix_scores_beatmap ON scores(beatmap_id, ruleset_id, passed, total_score DESC);
                CREATE INDEX IF NOT EXISTS ix_scores_user ON scores(user_id, ruleset_id, ended_at DESC);
                CREATE INDEX IF NOT EXISTS ix_scores_playlist ON scores(playlist_item_id, user_id);
                CREATE TABLE IF NOT EXISTS beatmaps (
                    id BIGINT PRIMARY KEY,
                    set_id BIGINT NOT NULL,
                    checksum TEXT,
                    status BIGINT NOT NULL DEFAULT 0,
                    json TEXT NOT NULL,
                    fetched_at BIGINT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS ix_beatmaps_checksum ON beatmaps(checksum);
                CREATE INDEX IF NOT EXISTS ix_beatmaps_set ON beatmaps(set_id);
                CREATE TABLE IF NOT EXISTS beatmapsets (
                    id BIGINT PRIMARY KEY,
                    json TEXT NOT NULL,
                    fetched_at BIGINT NOT NULL
                );
                -- channels 1 and 2 are seeded below.
                CREATE TABLE IF NOT EXISTS chat_channels (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 3) PRIMARY KEY,
