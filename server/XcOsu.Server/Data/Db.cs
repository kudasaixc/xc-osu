                """);

            // later additions go here as "ALTER TABLE … ADD COLUMN IF NOT EXISTS …".

            // rows carried over from installs that predate sessions and hashed tokens.
            exec(c, "UPDATE tokens SET session_id = md5(random()::text || clock_timestamp()::text || access_token) WHERE session_id IS NULL");
            using (var tx = c.BeginTransaction())
            {
                // Preserve existing sessions while migrating usable secrets to digests.
                foreach (var token in c.Query("SELECT access_token, refresh_token, expires_at FROM tokens WHERE length(access_token) = 64",
                    r => (access: r.GetString(0), refresh: r.GetString(1), expires: r.GetInt64(2))))
                    c.Exec("UPDATE tokens SET access_token = @a, refresh_token = @r, refresh_expires_at = @e, session_expires_at = @e WHERE access_token = @old",
                        ("@a", Services.Accounts.TokenHash(token.access)), ("@r", Services.Accounts.TokenHash(token.refresh)),
                        ("@e", token.expires + 30L * 86400), ("@old", token.access));
                tx.Commit();
            }

            exec(c, "SELECT pg_advisory_unlock(7203119)");
        }

        private static void exec(NpgsqlConnection c, string sql)
        {
            using var cmd = c.CreateCommand();
            cmd.CommandText = sql;
            cmd.ExecuteNonQuery();
        }

        public void Dispose() => source.Dispose();
    }

    /// <summary>
    /// One result row. Getters convert between numeric types the way the queries were written to expect
    /// (COUNT/SUM come back as bigint or numeric, comparisons as boolean) instead of insisting on the exact column type.
    /// </summary>
    public sealed class DbRow
    {
        private readonly NpgsqlDataReader reader;

        public DbRow(NpgsqlDataReader reader) => this.reader = reader;

        public int FieldCount => reader.FieldCount;

        public bool IsDBNull(int i) => reader.IsDBNull(i);

        public object GetValue(int i) => reader.GetValue(i);

        public long GetInt64(int i) => reader.GetValue(i) switch
        {
            long l => l,
            int n => n,
            short s => s,
            bool b => b ? 1 : 0,
            double d => (long)d,
            float f => (long)f,
            decimal m => (long)m,
            string s => long.Parse(s, CultureInfo.InvariantCulture),
            DBNull => 0,
            var other => Convert.ToInt64(other, CultureInfo.InvariantCulture),
        };

        public int GetInt32(int i) => checked((int)GetInt64(i));

        public bool GetBoolean(int i) => reader.GetValue(i) is bool b ? b : GetInt64(i) != 0;

        public double GetDouble(int i) => reader.GetValue(i) switch
        {
            double d => d,
            float f => f,
            long l => l,
            int n => n,
            short s => s,
            decimal m => (double)m,
            string s => double.Parse(s, CultureInfo.InvariantCulture),
            DBNull => 0,
            var other => Convert.ToDouble(other, CultureInfo.InvariantCulture),
        };

        public string GetString(int i) => reader.GetValue(i) switch
        {
            string s => s,
            DBNull => throw new InvalidCastException($"Column {i} is NULL."),
            var other => Convert.ToString(other, CultureInfo.InvariantCulture)!,
        };
    }

    public static class DbExtensions
    {
        /// <summary>Builds a command with named parameters ("@name"), given as ("@name", value) pairs.</summary>
        public static NpgsqlCommand Cmd(this NpgsqlConnection c, string sql, params (string name, object? value)[] args)
        {
            var cmd = c.CreateCommand();
            cmd.CommandText = sql;

            foreach (var (name, value) in args)
            {
                switch (value)
                {
                    case null:
                    case DBNull:
                        // untyped: takes the type of whatever it is compared with or assigned to.
                        cmd.Parameters.Add(new NpgsqlParameter(name, NpgsqlDbType.Unknown) { Value = DBNull.Value });
                        break;

                    case string s:
                        // sent untyped so the server reads it as the type of the column it meets (text, citext, or a number
                        // given as text). PostgreSQL text cannot hold NUL.
                        cmd.Parameters.Add(new NpgsqlParameter(name, NpgsqlDbType.Unknown) { Value = s.Contains('\0') ? s.Replace("\0", "") : s });
                        break;

                    case bool b:
                        cmd.Parameters.AddWithValue(name, b ? 1 : 0);
                        break;

                    case uint or ushort or byte or sbyte:
                        cmd.Parameters.AddWithValue(name, Convert.ToInt64(value));
                        break;

                    case ulong u:
                        cmd.Parameters.AddWithValue(name, checked((long)u));
                        break;

                    case Enum e:
                        cmd.Parameters.AddWithValue(name, Convert.ToInt64(e));
                        break;

                    case decimal m:
                        cmd.Parameters.AddWithValue(name, (double)m);
                        break;

                    case float f:
                        cmd.Parameters.AddWithValue(name, (double)f);
                        break;

                    default:
                        cmd.Parameters.AddWithValue(name, value);
                        break;
                }
            }

            return cmd;
        }

        /// <summary>Runs a statement; returns the number of rows it changed.</summary>
        public static long Exec(this NpgsqlConnection c, string sql, params (string, object?)[] args)
        {
            using var cmd = c.Cmd(sql, args);
            return cmd.ExecuteNonQuery();
        }

        public static T? Scalar<T>(this NpgsqlConnection c, string sql, params (string, object?)[] args)
        {
            using var cmd = c.Cmd(sql, args);
            object? r = cmd.ExecuteScalar();
            if (r == null || r is DBNull) return default;
            return (T)Convert.ChangeType(r, Nullable.GetUnderlyingType(typeof(T)) ?? typeof(T), CultureInfo.InvariantCulture);
        }

        /// <summary>Runs an INSERT into a table with an "id" column; returns the id of the new row.</summary>
        public static long Insert(this NpgsqlConnection c, string sql, params (string, object?)[] args)
        {
            using var cmd = c.Cmd(sql + " RETURNING id", args);
            return Convert.ToInt64(cmd.ExecuteScalar()!, CultureInfo.InvariantCulture);
        }

        public static List<T> Query<T>(this NpgsqlConnection c, string sql, Func<DbRow, T> map, params (string, object?)[] args)
        {
            using var cmd = c.Cmd(sql, args);
            using var r = cmd.ExecuteReader();
            var row = new DbRow(r);
            var list = new List<T>();
            while (r.Read())
                list.Add(map(row));
            return list;
        }

        /// <summary>True when a statement failed because the row already exists (two requests racing for the same name, token or slot).</summary>
        public static bool IsUniqueViolation(this Exception e) => e is PostgresException { SqlState: PostgresErrorCodes.UniqueViolation };
    }
