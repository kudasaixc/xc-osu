                CREATE TABLE IF NOT EXISTS playlist_items (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    room_id BIGINT NOT NULL,
                    json TEXT NOT NULL
                );
                CREATE INDEX IF NOT EXISTS ix_playlist_items_room ON playlist_items(room_id);
                INSERT INTO chat_channels (id, name, description, type) VALUES
                    (1, '#osu', 'General discussion for xc-osu!', 'PUBLIC'),
                    (2, '#announce', 'xc softworks announcements', 'PUBLIC')
                    ON CONFLICT (id) DO NOTHING;

