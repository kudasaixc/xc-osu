export function makeT(lang) {
  const l = lang === 'fr' ? 'fr' : 'en';
  const t = (key, ...args) => {
    const s = S[l][key] ?? S.en[key] ?? key;
    return args.length ? s.replace(/\{(\d)\}/g, (_, i) => args[+i]) : s;
  };
  t.lang = l;
  return t;
}
